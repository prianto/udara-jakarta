PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS operators (
  id         INTEGER PRIMARY KEY AUTOINCREMENT,
  name       TEXT NOT NULL UNIQUE,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now')),
  updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now'))
) STRICT;

CREATE TABLE IF NOT EXISTS stations (
  id                 INTEGER PRIMARY KEY AUTOINCREMENT,
  operator_id        INTEGER REFERENCES operators (id) ON UPDATE CASCADE ON DELETE SET NULL,
  uuid               TEXT NOT NULL UNIQUE,            -- uuid v4 / v7, generated by the app
  spku               TEXT,
  parameter          TEXT,
  sumber_data        TEXT,
  kecamatan          TEXT,
  kota               TEXT,
  lat                REAL CHECK (lat  BETWEEN -90  AND 90),
  long               REAL CHECK (long BETWEEN -180 AND 180),
  is_active          INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0, 1)),
  tahun_pengadaan    INTEGER CHECK (tahun_pengadaan BETWEEN 1900 AND 2100),
  perawatan_terakhir TEXT,                            -- date, YYYY-MM-DD
  created_at         TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now')),
  updated_at         TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now'))
) STRICT;

CREATE INDEX IF NOT EXISTS idx_stations_operator_id ON stations (operator_id);
CREATE INDEX IF NOT EXISTS idx_stations_kota        ON stations (kota);

CREATE TABLE IF NOT EXISTS measurements (
  id          INTEGER PRIMARY KEY AUTOINCREMENT,
  station_id  INTEGER REFERENCES stations (id) ON UPDATE CASCADE ON DELETE SET NULL,
  wind_speed  REAL,
  humidity    REAL,
  temperature REAL,
  pm25_index  INTEGER,
  pm10_index  INTEGER,
  co_index    INTEGER,
  so2_index   INTEGER,
  no2_index   INTEGER,
  o3_index    INTEGER,
  ispu_index  INTEGER,
  measured_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%d %H:%M:%S', 'now'))
) STRICT;

CREATE INDEX IF NOT EXISTS idx_measurements_station_time ON measurements (station_id, measured_at);

-- keep updated_at fresh on every update
CREATE TRIGGER IF NOT EXISTS trg_operators_updated_at
AFTER UPDATE ON operators
FOR EACH ROW WHEN NEW.updated_at = OLD.updated_at
BEGIN
  UPDATE operators SET updated_at = strftime('%Y-%m-%d %H:%M:%S', 'now') WHERE id = NEW.id;
END;

CREATE TRIGGER IF NOT EXISTS trg_stations_updated_at
AFTER UPDATE ON stations
FOR EACH ROW WHEN NEW.updated_at = OLD.updated_at
BEGIN
  UPDATE stations SET updated_at = strftime('%Y-%m-%d %H:%M:%S', 'now') WHERE id = NEW.id;
END;